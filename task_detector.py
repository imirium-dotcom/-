# ============================================================
# TEXT NORMALIZATION
# ============================================================

def _normalize(text):
    if not text:
        return ""

    text = str(text).strip().lower()

    # Убираем некоторые знаки препинания,
    # чтобы одинаковые фразы определялись одинаково.
    for symbol in (
        "?",
        "!",
        ",",
        ".",
        ";",
        ":",
    ):
        text = text.replace(symbol, "")

    # Убираем повторяющиеся пробелы.
    text = " ".join(text.split())

    return text


# ============================================================
# COMMAND DETECTION
# ============================================================

def _looks_like_command(text):
    for prefix in COMMAND_PREFIXES:

        if text == prefix:
            return True

        if text.startswith(prefix + " "):
            return True

    return False


# ============================================================
# TASK DETECTION
# ============================================================

def _looks_like_task(text):
    for pattern in TASK_PATTERNS:

        if pattern in text:
            return True

    return False


# ============================================================
# MAIN DETECTOR
# ============================================================

def detect_request_type(text):

    normalized = _normalize(text)

    if not normalized:
        return {
            "type": "unknown",
            "text": text,
            "confidence": 0.0
        }

    # --------------------------------------------------------
    # Сначала проверяем задачу.
    # --------------------------------------------------------

    if _looks_like_task(normalized):

        return {
            "type": "task",
            "text": text,
            "confidence": 1.0
        }

    # --------------------------------------------------------
    # Затем обычную команду.
    # --------------------------------------------------------

    if _looks_like_command(normalized):

        return {
            "type": "command",
            "text": text,
            "confidence": 1.0
        }

    # --------------------------------------------------------
    # Пока неизвестный тип.
    # --------------------------------------------------------

    return {
        "type": "unknown",
        "text": text,
        "confidence": 0.0
    }


# ============================================================
# SIMPLE HELPERS
# ============================================================

def is_task(text):
    result = detect_request_type(text)

    return result["type"] == "task"


def is_command(text):
    result = detect_request_type(text)

    return result["type"] == "command"


