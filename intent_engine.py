import re


def normalize_text(text):
    if not text:
        return ""

    text = text.lower().strip()
    text = re.sub(r"\s+", " ", text)

    return text


def detect_intent(text):
    text = normalize_text(text)

    # -------------------------
    # ПАМЯТЬ
    # -------------------------

    if any(word in text for word in [
        "запомни",
        "сохрани",
        "не забудь",
        "запиши в память"
    ]):
        return "remember"

    if any(word in text for word in [
        "вспомни",
        "напомни",
        "что ты помнишь",
        "что ты знаешь о"
    ]):
        return "recall"

    if any(word in text for word in [
        "забудь",
        "удали из памяти",
        "не помни"
    ]):
        return "forget"

    # -------------------------
    # ИНТЕРНЕТ
    # -------------------------

    if any(word in text for word in [
        "найди",
        "поищи",
        "посмотри в интернете",
        "проверь в интернете",
        "узнай в интернете",
        "поищи в сети",
        "найди в сети"
    ]):
        return "internet"

    # -------------------------
    # ФАЙЛЫ
    # -------------------------

    if any(word in text for word in [
        "открой файл",
        "прочитай файл",
        "покажи файл",
        "открыть файл",
        "прочитать файл"
    ]):
        return "file"

    # -------------------------
    # ПАПКИ
    # -------------------------

    if any(word in text for word in [
        "открой папку",
        "покажи папку",
        "открыть папку",
        "покажи директорию"
    ]):
        return "folder"

    # -------------------------
    # ЗАПУСК ПРОГРАММ
    # -------------------------

    if any(word in text for word in [
        "запусти",
        "открой программу",
        "запусти программу",
        "открой мне",
        "открой",
        "запустить",
        "открыть"
    ]):
        return "run_program"

    # -------------------------
    # СИСТЕМА
    # -------------------------

    if any(word in text for word in [
        "состояние системы",
        "проверь систему",
        "как система",
        "характеристики компьютера",
        "характеристики системы",
        "информация о системе",
        "характеристики пк",
        "сколько памяти",
        "сколько оперативной памяти",
        "сколько оперативки",
        "сколько ram",
        "загрузка процессора",
        "загрузку процессора",
        "нагрузка процессора",
        "нагрузку процессора",
        "загрузка cpu",
        "загрузку cpu",
        "нагрузка cpu",
        "нагрузку cpu",
        "процессор загружен"
    ]):
        return "system"

    # -------------------------
    # CMD
    # -------------------------

    if any(word in text for word in [
        "выполни команду",
        "выполни в cmd",
        "выполни команду cmd",
        "запусти команду"
    ]):
        return "command"

    # -------------------------
    # ВОЗМОЖНОСТИ AI
    # -------------------------

    if any(word in text for word in [
        "что ты можешь",
        "что ты умеешь",
        "какие у тебя возможности",
        "покажи что ты умеешь",
        "покажи, что ты умеешь",
        "покажи возможности",
        "расскажи что ты умеешь",
        "расскажи, что ты умеешь",
        "что ты способен делать"
    ]):
        return "capabilities"

    # -------------------------
    # ЗАВЕРШЕНИЕ
    # -------------------------

    if any(word in text for word in [
        "выход",
        "заверши работу",
        "завершить работу",
        "остановись",
        "остановить работу",
        "выключись",
        "выключи себя"
    ]):
        return "exit"

    return "unknown"


def extract_parameter(text, intent):
    text = normalize_text(text)

    # -------------------------
    # ПАМЯТЬ
    # -------------------------

    if intent == "remember":

        patterns = [
            r"запомни(?:,)? что (.+)",
            r"сохрани(?:,)? что (.+)",
            r"не забудь(?:,)? что (.+)",
            r"запиши в память(?:,)? что (.+)"
        ]

    # -------------------------
    # ВСПОМНИТЬ
    # -------------------------

    elif intent == "recall":

        patterns = [
            r"вспомни (.+)",
            r"напомни (.+)",
            r"что ты помнишь (.+)",
            r"что ты знаешь о (.+)"
        ]

    # -------------------------
    # ЗАБЫТЬ
    # -------------------------

    elif intent == "forget":

        patterns = [
            r"забудь (.+)",
            r"удали из памяти (.+)",
            r"не помни (.+)"
        ]

    # -------------------------
    # ИНТЕРНЕТ
    # -------------------------

    elif intent == "internet":

        patterns = [
            r"найди в интернете (.+)",
            r"найди в сети (.+)",
            r"найди (.+)",
            r"поищи в интернете (.+)",
            r"поищи в сети (.+)",
            r"поищи (.+)",
            r"посмотри в интернете (.+)",
            r"проверь в интернете (.+)",
            r"узнай в интернете (.+)"
        ]

    # -------------------------
    # ФАЙЛЫ
    # -------------------------

    elif intent == "file":

        patterns = [
            r"открой файл (.+)",
            r"прочитай файл (.+)",
            r"покажи файл (.+)",
            r"открыть файл (.+)",
            r"прочитать файл (.+)"
        ]

    # -------------------------
    # ПАПКИ
    # -------------------------

    elif intent == "folder":

        patterns = [
            r"открой папку (.+)",
            r"покажи папку (.+)",
            r"открыть папку (.+)",
            r"покажи директорию (.+)"
        ]

    # -------------------------
    # ПРОГРАММЫ
    # -------------------------

    elif intent == "run_program":

        patterns = [
            r"запусти программу (.+)",
            r"открой программу (.+)",
            r"запусти (.+)",
            r"запустить (.+)",
            r"открой мне (.+)",
            r"открой (.+)",
            r"открыть (.+)"
        ]

    # -------------------------
    # CMD
    # -------------------------

    elif intent == "command":

        patterns = [
            r"выполни команду cmd (.+)",
            r"выполни команду (.+)",
            r"выполни в cmd (.+)",
            r"запусти команду (.+)"
        ]

    else:
        return None

    for pattern in patterns:

        match = re.search(pattern, text)

        if match:
            return match.group(1).strip()

    return None


def understand(text):
    normalized = normalize_text(text)

    intent = detect_intent(normalized)

    parameter = extract_parameter(
        normalized,
        intent
    )

    return {
        "text": normalized,
        "intent": intent,
        "parameter": parameter
    }


